import http from "k6/http";
import { check } from "k6";
import { Counter } from "k6/metrics";
import { BASE_URL } from "../lib/config.js";

// REAL LOAD SCENARIO -- exercises Phase 12 rate limiting AND backpressure
// under real generated throughput against a live API/Postgres/RabbitMQ
// stack (deadletter_load, per the existing Phase 11 isolation
// convention -- see docs/load-testing.md).
//
// UNLIKE every earlier scenario (A-E), a 429 or 503 here is NOT
// automatically a failure -- both are expected, legitimate outcomes of
// this scenario's own design. k6's built-in http_req_failed metric only
// counts non-2xx/3xx responses as "failed" by default, so 429/503 WILL
// show up in k6's own summary as failures. That is expected and is
// explicitly NOT the pass/fail signal here -- see the custom
// status_201/status_429/status_503/status_other Counters below (and
// docs/load-testing.md's Phase 12 section) for the actual, separately-
// reported HTTP status-code distribution.
//
// Client identity: every real request generated by k6 running on this
// single host shares ONE source IP, which would otherwise collapse all
// VUs into a single rate-limit bucket and prevent generating enough
// AGGREGATE throughput to meaningfully stress backpressure (which is a
// system-wide signal, not a per-client one). Each VU therefore sets its
// own X-Test-Client-Id (k6-vu-<VU id>) -- the TEST-ONLY identity
// override documented in rateLimiter.ts, active only because this run
// targets an API process with NODE_ENV=development, never trusted in
// production. This is a deliberate, inspected choice, not an invented
// deployment semantic -- see docs/engineering-decisions.md.
//
// Whether pendingOutboxEvents actually exceeds BACKPRESSURE_THRESHOLD
// (50) during this run depends on real throughput vs. the real
// dispatcher drain rate (BATCH_SIZE=10 every POLL_INTERVAL_MS=2000, i.e.
// ~5 events/sec sustained) -- NOT forced or simulated here. If the
// actual submission rate this run achieves does not exceed that drain
// rate for long enough, zero 503s is the correct, honest result. See
// docs/load-testing.md for what this specific run actually produced.

export const options = {
  scenarios: {
    rate_limit_backpressure: {
      executor: "constant-vus",
      vus: 20,
      duration: "20s",
    },
  },
};

const status201 = new Counter("status_201");
const status429 = new Counter("status_429");
const status503 = new Counter("status_503");
const statusOther = new Counter("status_other");

export default function () {
  const clientId = `k6-vu-${__VU}`;

  const res = http.post(
    `${BASE_URL}/api/jobs`,
    JSON.stringify({ type: "load_test_rate_limit_backpressure", payload: {} }),
    { headers: { "Content-Type": "application/json", "X-Test-Client-Id": clientId } }
  );

  if (res.status === 201) {
    status201.add(1);
  } else if (res.status === 429) {
    status429.add(1);
  } else if (res.status === 503) {
    status503.add(1);
  } else {
    statusOther.add(1);
  }

  check(res, {
    "status is 201, 429, or 503 (all three are legitimate outcomes for this scenario)": (r) =>
      r.status === 201 || r.status === 429 || r.status === 503,
  });
}
